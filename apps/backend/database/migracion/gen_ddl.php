function pgtype($ct, $extra, &$pre, $tabla, $col, $c) {
  $base = trim(str_replace('unsigned','',preg_replace('/\(.*/','',$ct)));
  if (preg_match('/^enum\((.*)\)$/i', $ct, $m)) {
    $vals = str_getcsv($m[1], ',', "'");
    $r = mysqli_query($c, "SELECT COUNT(*) n FROM `$tabla` WHERE `$col`=''");
    $x = $r ? mysqli_fetch_assoc($r) : ['n'=>0];
    if ($x['n'] > 0) $vals[] = '';
    $vals = array_values(array_unique($vals));          // MySQL admite etiquetas repetidas; PostgreSQL no
    $tn = strtolower($tabla."_".$col."_enum");
    $pre[] = "CREATE TYPE $tn AS ENUM (".implode(', ', array_map(fn($v)=>"'".str_replace("'","''",$v)."'", $vals)).");";
    return $tn;
  }
  if (preg_match('/^decimal\(([\d,]+)\)/i',$ct,$m)) return "numeric($m[1])";
  if (preg_match('/^(varchar|char)\((\d+)\)/i',$ct,$m)) return strtolower($m[1])."($m[2])";
  return match($base) {
    'int','mediumint' => 'integer', 'bigint' => 'bigint',
    'smallint','tinyint' => 'smallint',
    'double' => 'double precision', 'float' => 'real',
    'text','mediumtext','longtext','tinytext' => 'text',
    'date' => 'date', 'datetime','timestamp' => 'timestamp', 'time' => 'time',
    'year' => 'smallint', 'blob','mediumblob','longblob' => 'bytea',
    default => 'text',
  };
}

$r = mysqli_query($c,"SELECT table_name FROM information_schema.tables WHERE table_schema=DATABASE() AND table_type='BASE TABLE' ORDER BY table_name");
