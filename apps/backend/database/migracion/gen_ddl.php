  $cols = []; $pk = [];
  $r = mysqli_query($c,"SELECT column_name,column_type,is_nullable,column_default,extra FROM information_schema.columns WHERE table_schema=DATABASE() AND table_name='$t' ORDER BY ordinal_position");
  while($x = mysqli_fetch_assoc($r)) {
    $tp = pgtype($x['column_type'], $x['extra'], $pre, $t, $x['column_name'], $c);
    $line = '  "'.$x['column_name'].'" '.$tp;
    if (str_contains($x['extra'],'auto_increment')) $line .= ' GENERATED BY DEFAULT AS IDENTITY';
    elseif ($x['column_default'] !== null) {
      $d = $x['column_default'];
      $lit = (strlen($d) > 1 && $d[0] === "'" && substr($d,-1) === "'");
      if ($lit) $d = substr($d, 1, -1);                  // MariaDB devuelve los literales entrecomillados
      if (preg_match('/^0000-00-00/', $d) || strtoupper($d) === 'NULL') {
        $descartados[] = "$t.".$x['column_name']." (default invalido '$d')"; $d = null;
      } elseif (!$lit && preg_match('/current_timestamp/i', $d)) $d = 'CURRENT_TIMESTAMP';
      elseif ($lit || !is_numeric($d)) $d = "'".str_replace("'","''",$d)."'";
      if ($d !== null) $line .= " DEFAULT $d";
    }
    if ($x['is_nullable'] === 'NO') $line .= ' NOT NULL';
    $cols[] = $line;
  }
  $r = mysqli_query($c,"SELECT column_name FROM information_schema.statistics WHERE table_schema=DATABASE() AND table_name='$t' AND index_name='PRIMARY' ORDER BY seq_in_index");
  while($x = mysqli_fetch_assoc($r)) $pk[] = '"'.$x['column_name'].'"';
  if ($pk) $cols[] = '  PRIMARY KEY ('.implode(', ',$pk).')';
  $body[] = "CREATE TABLE \"$t\" (\n".implode(",\n",$cols)."\n);";
}

$idx = [];
